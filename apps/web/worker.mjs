import { production as buildEnv } from "./.open-next/cloudflare/next-env.mjs";

const RETENTION_DAYS = 365;
const DAY_MS = 24 * 60 * 60 * 1000;

// ── Fast path (raw handlers ahead of the Next server) ─────────────────────
// The Next/OpenNext machinery costs 7-10ms CPU per request (p50), which is
// the entire free-plan CPU budget. The hot mobile routes are pure pass-
// through proxies, so serve them with minimal handlers here and fall back to
// the Next handler for anything unexpected. Keep behavior byte-compatible
// with the Next routes they shadow:
//   tmdb     → app/api/tmdb/[...tmdb]/route.ts   (incl. trim=1 + edge cache)
//   movies/tv → app/api/movies/route.ts + tmdb.server.ts getMovies/getTVShows

const TMDB_BASE = "https://api.themoviedb.org/3";

const TMDB_CACHE_HEADERS =
  "public, s-maxage=86400, stale-while-revalidate=86400";
const DISCOVER_CACHE_HEADERS =
  "public, s-maxage=600, stale-while-revalidate=3600";

const ALLOWED_ORIGINS = [
  "https://filmsnap-pro.netlify.app",
  "https://filmsnaps1.anonymous260260a.workers.dev",
  "app://index.html",
  "app://",
];

const CORS_ALLOW_HEADERS =
  "Content-Type, Authorization, X-Client, X-App-Version, X-Anon-Id";

function rawCors(origin) {
  const o = origin || "app://index.html";
  return {
    "Access-Control-Allow-Origin": ALLOWED_ORIGINS.includes(o)
      ? o
      : ALLOWED_ORIGINS[0],
    "Access-Control-Allow-Methods": "GET, OPTIONS",
    "Access-Control-Allow-Headers": CORS_ALLOW_HEADERS,
    "Access-Control-Max-Age": "86400",
    Vary: "Origin",
  };
}

function rawJson(data, origin, status, cacheControl) {
  const headers = {
    "Content-Type": "application/json",
    ...rawCors(origin),
  };
  if (cacheControl) headers["Cache-Control"] = cacheControl;
  return new Response(JSON.stringify(data), { status, headers });
}

function edgeCacheOpts(ttl, negativeTtl = 60) {
  return {
    cf: {
      cacheEverything: true,
      cacheTtlByStatus: {
        "200-299": ttl,
        "404": negativeTtl,
        "403": 0,
        "401": 0,
        "429": 0,
        "500-599": 0,
      },
    },
  };
}

function tmdbTtl(path) {
  if (/^\/search\//.test(path)) return 600;
  if (
    /(trending|popular|upcoming|top_rated|now_playing|airing_today|on_the_air)/.test(
      path,
    )
  ) {
    return 600;
  }
  if (/\/external_ids$/.test(path)) return 604800;
  if (/^\/(movie|tv|person)\/\d+/.test(path)) return 86400;
  return 3600;
}

// DUPLICATED from app/api/tmdb/[...tmdb]/route.ts (trimDetailPayload) —
// keep both copies in sync; mobile appends &trim=1 and expects the exact
// same slim payload shape from either handler.
function trimDetailPayload(data, isTv) {
  if (!data || typeof data !== "object") return data;

  const pick = (src, keys) => {
    const out = {};
    if (!src || typeof src !== "object") return out;
    for (const k of keys) {
      if (src[k] !== undefined) out[k] = src[k];
    }
    return out;
  };

  const topKeys = isTv
    ? [
        "id",
        "name",
        "original_name",
        "overview",
        "poster_path",
        "backdrop_path",
        "vote_average",
        "vote_count",
        "first_air_date",
        "genres",
        "episode_run_time",
        "status",
        "number_of_seasons",
        "number_of_episodes",
        "tagline",
        "popularity",
        "original_language",
      ]
    : [
        "id",
        "title",
        "original_title",
        "overview",
        "poster_path",
        "backdrop_path",
        "vote_average",
        "vote_count",
        "release_date",
        "runtime",
        "genres",
        "status",
        "tagline",
        "popularity",
        "original_language",
        "budget",
        "revenue",
      ];

  const out = pick(data, topKeys);

  if (Array.isArray(data.genres)) {
    out.genres = data.genres.map((g) => pick(g, ["id", "name"]));
  }

  if (data.credits) {
    const cast = Array.isArray(data.credits.cast) ? data.credits.cast : [];
    const creditsOut = {
      cast: cast
        .slice(0, 15)
        .map((c) =>
          pick(c, ["id", "name", "character", "profile_path", "order", "cast_id"]),
        ),
    };
    if (Array.isArray(data.credits.crew) && data.credits.crew.length) {
      const directors = data.credits.crew
        .filter((c) => c.job === "Director")
        .slice(0, 3)
        .map((c) => pick(c, ["id", "name", "job", "profile_path"]));
      if (directors.length) creditsOut.crew = directors;
    }
    out.credits = creditsOut;
  }

  if (data.videos) {
    const results = Array.isArray(data.videos.results) ? data.videos.results : [];
    out.videos = {
      results: results
        .filter(
          (v) =>
            v.site === "YouTube" &&
            (v.type === "Trailer" || v.type === "Teaser"),
        )
        .slice(0, 6)
        .map((v) => pick(v, ["key", "name", "type", "site", "size"])),
    };
  }

  if (data.similar) {
    const results = Array.isArray(data.similar.results) ? data.similar.results : [];
    out.similar = {
      ...pick(data.similar, ["page", "total_pages", "total_results"]),
      results: results
        .slice(0, 20)
        .map((m) =>
          pick(m, [
            "id",
            "title",
            "name",
            "poster_path",
            "backdrop_path",
            "vote_average",
            "release_date",
            "first_air_date",
            "media_type",
            "overview",
          ]),
        ),
    };
  }

  if (data.recommendations) {
    const results = Array.isArray(data.recommendations.results)
      ? data.recommendations.results
      : [];
    out.recommendations = {
      ...pick(data.recommendations, ["page", "total_pages", "total_results"]),
      results: results
        .slice(0, 20)
        .map((m) =>
          pick(m, [
            "id",
            "title",
            "name",
            "poster_path",
            "backdrop_path",
            "vote_average",
            "release_date",
            "first_air_date",
            "media_type",
            "overview",
          ]),
        ),
    };
  }

  if (isTv && Array.isArray(data.seasons)) {
    out.seasons = data.seasons.map((s) =>
      pick(s, ["id", "season_number", "episode_count", "name", "air_date", "poster_path"]),
    );
  }

  if (isTv && Array.isArray(data.episode_run_time)) {
    out.episode_run_time = data.episode_run_time;
  }

  return out;
}

async function handleTmdb(request, url, apiKey) {
  const origin = request.headers.get("origin");
  const segs = url.pathname.slice("/api/tmdb/".length).split("/").filter(Boolean);
  if (!segs.length) return null;

  const sp = new URLSearchParams(url.search);
  const wantsTrim = sp.get("trim") === "1";
  sp.delete("trim");
  const query = sp.toString();

  const endpoint = `/${segs.join("/")}`;
  const upstreamPath = `${TMDB_BASE}${endpoint}${query ? `?${query}&` : "?"}api_key=${apiKey}`;

  const res = await fetch(upstreamPath, {
    headers: {
      "Cache-Control": "public, s-maxage=3600, stale-while-revalidate=86400",
    },
    ...edgeCacheOpts(tmdbTtl(endpoint), 300),
  });

  if (!res.ok) {
    const body = await res.text().catch(() => "");
    return rawJson(
      { error: `TMDB request failed (${res.status}): ${body.slice(0, 200)}` },
      origin,
      res.status,
    );
  }

  let data = await res.json();

  if (
    wantsTrim &&
    (segs[0] === "movie" || segs[0] === "tv") &&
    segs[1] &&
    /^\d+$/.test(segs[1])
  ) {
    data = trimDetailPayload(data, segs[0] === "tv");
  }

  return rawJson(data, origin, 200, TMDB_CACHE_HEADERS);
}

function discoverPath(type, sp) {
  const page = Number(sp.get("page") || 1);
  const sortBy = sp.get("sortBy") || "popularity.desc";
  const yearStart = Number(sp.get("yearStart") || (type === "movie" ? 1900 : 1950));
  const yearEnd = Number(sp.get("yearEnd") || new Date().getFullYear());
  const minRating = Number(sp.get("minRating") || 0);
  const maxRating = Number(sp.get("maxRating") || 10);
  const genres = sp.get("genres")?.split(",").map(Number);
  const language = sp.get("language") || undefined;

  let path = `/discover/${type}?sort_by=${sortBy}&page=${page}`;
  if (genres?.length) path += `&with_genres=${genres.join(",")}`;
  if (yearStart && yearEnd) {
    if (type === "movie") {
      path += `&primary_release_date.gte=${yearStart}-01-01&primary_release_date.lte=${yearEnd}-12-31`;
    } else {
      path += `&first_air_date.gte=${yearStart}-01-01&first_air_date.lte=${yearEnd}-12-31`;
    }
  }
  path += `&vote_average.gte=${minRating}`;
  path += `&vote_average.lte=${maxRating}`;
  if (language) path += `&with_original_language=${language}`;
  return path;
}

async function handleDiscover(request, url, apiKey, type) {
  const origin = request.headers.get("origin");
  const page = Number(url.searchParams.get("page") || 1);
  try {
    const res = await fetch(
      `${TMDB_BASE}${discoverPath(type, url.searchParams)}&api_key=${apiKey}`,
      edgeCacheOpts(3600),
    );
    if (!res.ok) {
      return rawJson({ results: [] }, origin, 200, DISCOVER_CACHE_HEADERS);
    }
    const data = await res.json();
    return rawJson(data, origin, 200, DISCOVER_CACHE_HEADERS);
  } catch (err) {
    return rawJson({ results: [], page, total_pages: 0 }, origin, 500);
  }
}

async function fastPath(request, env, url) {
  const p = url.pathname;
  let route = null;
  if (p.startsWith("/api/tmdb/")) route = "tmdb";
  else if (p === "/api/movies") route = "movie";
  else if (p === "/api/tv") route = "tv";
  if (!route) return null;

  if (request.method === "OPTIONS") {
    return new Response(null, {
      status: 204,
      headers: rawCors(request.headers.get("origin")),
    });
  }
  if (request.method !== "GET") return null;

  const apiKey = env?.TMDB_API_KEY || buildEnv?.TMDB_API_KEY;
  if (!apiKey) return null;

  if (route === "tmdb") return handleTmdb(request, url, apiKey);
  return handleDiscover(request, url, apiKey, route);
}

// ── Rate limiting & abuse protection (per-IP, in-memory) ──────────────────
// Free plan + workers.dev = no zone WAF available, so enforcement lives here.
// Windowed counters keyed by CF-Connecting-IP (Cloudflare-injected, cannot be
// spoofed). Approximate across isolates/colos — an abuser may see N× the
// limit; exact global enforcement would need a Durable Object (phase 2).
const RL_WINDOW_MS = 60_000;
const RL_GLOBAL_API = 150; // per IP, all /api/*
const RL_EXPENSIVE = 30; // per IP, upstream-quota-burning routes
const RL_TELEMETRY_IP = 10; // per IP, D1-write budget protection
const RL_TELEMETRY_GLOBAL = 600; // all IPs, distributed-spam floor
const RL_FEEDBACK = 3; // per hour — nobody legitimately submits 3+ feedbacks/hour
const RL_FEEDBACK_WINDOW_MS = 3_600_000;
const RL_MAX_BODY_BYTES = 64 * 1024;
const RL_MAX_TRACKED_IPS = 10_000;

const rateBuckets = new Map();
let telemetryGlobalBucket = { count: 0, windowStart: 0 };

function clientIpOf(request) {
  const cfi = request.headers.get("CF-Connecting-IP");
  if (cfi) return cfi.trim();
  const xff = request.headers.get("X-Forwarded-For");
  if (xff) return xff.split(",")[0].trim();
  return "unknown";
}

function isExpensivePath(p) {
  return (
    p.startsWith("/api/player/") ||
    p === "/api/stream" ||
    p.startsWith("/api/stream/") ||
    p === "/api/subtitles" ||
    p.startsWith("/api/subtitles/") ||
    p === "/api/anime/resolve"
  );
}

function bumpBucket(map, key, limit, now, windowMs = RL_WINDOW_MS) {
  let b = map.get(key);
  if (!b || now - b.windowStart >= windowMs) {
    b = { count: 0, windowStart: now };
    map.set(key, b);
  }
  b.count += 1;
  return b.count > limit;
}

function pruneRateBuckets(now) {
  if (rateBuckets.size <= RL_MAX_TRACKED_IPS) return;
  for (const [k, b] of rateBuckets) {
    if (now - b.windowStart >= RL_WINDOW_MS) rateBuckets.delete(k);
    if (rateBuckets.size <= RL_MAX_TRACKED_IPS / 2) break;
  }
}

function rateLimitReject(status, message) {
  return new Response(JSON.stringify({ error: message }), {
    status,
    headers: {
      "Content-Type": "application/json",
      "Retry-After": "30",
      ...rawCors(null),
    },
  });
}

function rateLimitCheck(request, url) {
  const p = url.pathname;
  if (!p.startsWith("/api/")) return null;
  if (request.method === "OPTIONS") return null;

  const now = Date.now();
  const cl = Number(request.headers.get("content-length") || 0);
  if (cl > RL_MAX_BODY_BYTES) {
    return rateLimitReject(413, "payload too large");
  }

  const ip = clientIpOf(request);

  if (p === "/api/feedback" && request.method === "POST") {
    if (bumpBucket(rateBuckets, "f:" + ip, RL_FEEDBACK, now, RL_FEEDBACK_WINDOW_MS)) {
      pruneRateBuckets(now);
      return rateLimitReject(429, "rate limited");
    }
    return null;
  }

  if (p === "/api/telemetry" && request.method === "POST") {
    if (
      !telemetryGlobalBucket.count ||
      now - telemetryGlobalBucket.windowStart >= RL_WINDOW_MS
    ) {
      telemetryGlobalBucket = { count: 0, windowStart: now };
    }
    telemetryGlobalBucket.count += 1;
    if (telemetryGlobalBucket.count > RL_TELEMETRY_GLOBAL) {
      return rateLimitReject(429, "rate limited");
    }
    if (bumpBucket(rateBuckets, "t:" + ip, RL_TELEMETRY_IP, now)) {
      pruneRateBuckets(now);
      return rateLimitReject(429, "rate limited");
    }
    return null;
  }

  let limited = bumpBucket(rateBuckets, "g:" + ip, RL_GLOBAL_API, now);
  if (!limited && isExpensivePath(p)) {
    limited = bumpBucket(rateBuckets, "e:" + ip, RL_EXPENSIVE, now);
  }
  pruneRateBuckets(now);
  return limited ? rateLimitReject(429, "rate limited") : null;
}

// ── Version telemetry (per-request app/client accounting) ──────────────────
// Every /api/* request is counted into Analytics Engine (AE_REQUESTS, exact
// aggregate counts per client/version/route) and, at a 1-in-N sample rate,
// upserted into the D1 version_ping_sample table so the admin dashboard can
// estimate DISTINCT installs per app version. Must match the
// 'sample_one_in' row in migrations/004_version_ping.sql.
const VERSION_SAMPLE_ONE_IN = 10;
const VERSION_PING_RETENTION_DAYS = 120;

const KNOWN_CLIENTS = new Set([
  "mobile-android",
  "mobile-ios",
  "desktop",
  "web",
  "ssr",
]);

function routeClassOf(pathname) {
  const p = pathname.replace(/^\/api\//, "");
  if (p.startsWith("tmdb")) return "tmdb";
  if (p.startsWith("telemetry")) return "telemetry";
  if (p.startsWith("stream")) return "stream";
  if (p.startsWith("player")) return "player";
  if (p.startsWith("anime")) return "anime";
  if (p.startsWith("subtitles")) return "subtitles";
  if (p.startsWith("blocklist")) return "blocklist";
  return p.split("/")[0] || "root";
}

function headerVal(request, name, maxLen) {
  const raw = request.headers.get(name);
  if (!raw) return "";
  const v = raw.trim();
  return v.length > maxLen ? v.slice(0, maxLen) : v;
}

function recordRequest(env, request, status, durationMs, ctx) {
  try {
    if (!env || !env.AE_REQUESTS) return;
    const url = new URL(request.url);
    if (!url.pathname.startsWith("/api/")) return;

    const clientRaw = headerVal(request, "x-client", 32);
    const client = KNOWN_CLIENTS.has(clientRaw) ? clientRaw : "unknown";
    const appVersion = headerVal(request, "x-app-version", 32);
    const routeClass = routeClassOf(url.pathname);

    env.AE_REQUESTS.writeDataPoint({
      indexes: [client],
      blobs: [client, appVersion, routeClass, url.pathname.slice(0, 128)],
      doubles: [status || 0, durationMs],
    });

    const sampledRow = {
      day: new Date().toISOString().slice(0, 10),
      client,
      appVersion,
      anonId: headerVal(request, "x-anon-id", 64),
    };
    if (ctx && typeof ctx.waitUntil === "function") {
      ctx.waitUntil(insertVersionSample(env, sampledRow));
    } else {
      void insertVersionSample(env, sampledRow);
    }
  } catch {
    // Never let accounting break the request pipeline.
  }
}

async function insertVersionSample(env, row) {
  try {
    if (!env.TELEMETRY_DB) return;
    if (Math.random() >= 1 / VERSION_SAMPLE_ONE_IN) return;
    await env.TELEMETRY_DB.prepare(
      `INSERT INTO version_ping_sample
         (day, client, app_version, anon_id, requests, updated_at)
       VALUES (?1, ?2, ?3, ?4, 1, ?5)
       ON CONFLICT (day, client, app_version, anon_id)
         DO UPDATE SET requests = requests + 1, updated_at = ?5`,
    )
      .bind(
        row.day,
        row.client,
        row.appVersion,
        row.anonId,
        Date.now(),
      )
      .run();
  } catch {
    // Sampled accounting is best-effort only.
  }
}

async function purgeVersionSamples(env) {
  const db = env && env.TELEMETRY_DB;
  if (!db) return;
  const cutoff = new Date(
    Date.now() - VERSION_PING_RETENTION_DAYS * DAY_MS,
  )
    .toISOString()
    .slice(0, 10);
  try {
    const result = await db
      .prepare("DELETE FROM version_ping_sample WHERE day < ?")
      .bind(cutoff)
      .run();
    console.log(
      `[retention] purged ${result.meta.changes} version_ping_sample rows older than ${VERSION_PING_RETENTION_DAYS} days`,
    );
  } catch (err) {
    console.error("[retention] version_ping_sample purge failed", err);
  }
}

/**
 * Feedback retention (privacy policy: 12 months). Rows carry the sender's
 * message, the reply, the optional email and the per-install token, so they
 * are removed together. Anti-abuse bookkeeping is swept in the same pass:
 * expired challenges and stale strike rows are inert and never needed again.
 * A missing table (migration not applied) must not stop the other purges.
 */
async function purgeFeedback(db, now = Date.now()) {
  const cutoffMs = now - RETENTION_DAYS * DAY_MS;
  const jobs = [
    ["feedback", "DELETE FROM feedback WHERE ts < ?1", [cutoffMs]],
    ["feedback_prompt", "DELETE FROM feedback_prompt WHERE ts < ?1", [cutoffMs]],
    ["feedback_challenge", "DELETE FROM feedback_challenge WHERE expires_at < ?1", [now]],
    [
      "feedback_strike",
      "DELETE FROM feedback_strike WHERE muted_until < ?1 AND window_start < ?2",
      [now, now - DAY_MS],
    ],
  ];
  for (const [table, sql, params] of jobs) {
    try {
      const result = await db
        .prepare(sql)
        .bind(...params)
        .run();
      if ((result.meta.changes ?? 0) > 0) {
        console.log(`[retention] purged ${result.meta.changes} ${table} rows`);
      }
    } catch {
      // Table missing — migration not applied on this database.
    }
  }
}

async function wrappedFetch(request, env, ctx) {
  const startMs = Date.now();
  try {
    const url = new URL(request.url);
    let res = rateLimitCheck(request, url);
    if (!res) {
      try {
        res = await fastPath(request, env, url);
      } catch {
        res = null;
      }
      if (!res) {
        res = await handler.fetch(request, env, ctx);
      }
    }
    recordRequest(env, request, res && res.status, Date.now() - startMs, ctx);
    return res;
  } catch (err) {
    recordRequest(env, request, 0, Date.now() - startMs, ctx);
    throw err;
  }
}

export default {
  fetch: wrappedFetch,

  async scheduled(event, env, ctx) {
    const runPurge = async () => {
      const db = env && env.TELEMETRY_DB;
      if (!db) {
        console.error("[retention] TELEMETRY_DB binding missing — skipping purge");
        return;
      }
      const cutoffMs = Date.now() - RETENTION_DAYS * DAY_MS;
      try {
        const result = await db
          .prepare("DELETE FROM telemetry_events WHERE ts < ?")
          .bind(cutoffMs)
          .run();
        console.log(
          `[retention] purged ${result.meta.changes} telemetry_events older than ${RETENTION_DAYS} days`,
        );
      } catch (err) {
        console.error("[retention] purge failed", err);
      }
      await purgeVersionSamples(env);
      await purgeFeedback(db);
    };

    if (event && typeof event.waitUntil === "function") {
      event.waitUntil(runPurge());
    } else if (ctx && typeof ctx.waitUntil === "function") {
      ctx.waitUntil(runPurge());
    } else {
      await runPurge();
    }
  },
};

